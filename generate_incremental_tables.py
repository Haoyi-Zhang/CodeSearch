#!/usr/bin/env python3
"""Generate two manuscript tables from the separately replayed comparison."""
import json
from pathlib import Path
from replay_incremental import replay_report

ROOT = Path(__file__).resolve().parent


def read(stem, directory=None, *, select=None):
    directory = Path(directory) if directory is not None else ROOT/'results'
    report, replay = replay_report(stem,directory,select=select)
    print(json.dumps({'report':stem,'verification':replay},sort_keys=True))
    return [report['trials'][i] for i in replay['replayed_trial_indices']]


def table(path, caption, label, headings, rows, *, check_only=False):
    lines = ['% Generated by artifact/generate_incremental_tables.py.', '\\begin{table}[t]',
             '\\centering', '\\small', '\\caption{'+caption+'}', '\\label{'+label+'}',
             '\\begin{tabular}{l'+'r'*(len(headings)-1)+'}', '\\toprule',
             ' & '.join(headings)+r' \\', '\\midrule']
    lines += [' & '.join(str(v) for v in row)+r' \\' for row in rows]
    lines += ['\\bottomrule', '\\end{tabular}', '\\end{table}']
    text='\n'.join(lines)+'\n'
    if check_only:
        if path.read_text(encoding='utf-8') != text:
            raise ValueError('incremental table disagrees with current replay: '+path.name)
    else:
        path.write_text(text, encoding='utf-8')


def census_table(directory, *, check_only=False, paper_dir=None):
    generated = read('incremental-generated', directory/'generated',select=lambda t:t['capacity']==5 and t['index_lag']==2)
    # read() just performed the source-work census as part of current replay.
    rows = []
    for policy, label in [('continuation', 'Continuation'), ('extra-local', 'Local extra/refill'),
                          ('extra-global', 'Global extra/refill')]:
        matched = [t for t in generated if t['policy'] == policy and t['capacity'] == 5]
        if len(matched) != 2 or {t['seed'] for t in matched} != {2, 3}:
            raise ValueError('census matched histories')
        cells = [sum(t['source_work_by_phase'][p].get(k, 0) for t in matched)
                 for p, k in [('initialization', 'posting_membership_updates'),
                              ('maintenance', 'posting_membership_updates'),
                              ('acquisition', 'posting_visits'), ('refill', 'posting_visits')]]
        rows.append([label]+[f'{v:,}' for v in cells])
    paper=Path(paper_dir) if paper_dir is not None else ROOT.parent/'paper'
    table(paper/'generated/incremental_census_table.tex',
          'Source-work census for the two generated histories at capacity 5 and lag 2. Initialization and update columns count posting membership operations; acquisition and refill columns count posting entries visited.',
          'tab:incremental-census', ['Policy', 'Initialization', 'Updates', 'Acquisition', 'Refill'], rows, check_only=check_only)
    print(json.dumps({'result': 'PASS', 'tables': 1, 'freshly_replayed_table_trials': len(generated)}))


def main(census_root=None, *, check_only=False, paper_dir=None):
    paper = Path(paper_dir) if paper_dir is not None else ROOT.parent/'paper'
    if not paper.is_dir():
        raise ValueError('optional sibling manuscript is absent; summaries remain usable')
    if census_root is not None:
        return census_table(census_root, check_only=check_only, paper_dir=paper)
    public = read('incremental-comparison',select=lambda t:t['capacity']==10 and t['index_lag']==2)
    generated = read('incremental-generated',select=lambda t:t['capacity']==5 and t['index_lag']==2)
    labels = {'ordinary': 'Original ordinary', 'directed': 'Original directed',
              'base-independent': 'Base-only selected'}
    rows = []
    for group, label in labels.items():
        matched = [t for t in public if t['query_group'] == group and t['capacity'] == 10
                   and t['index_lag'] == 2]
        if len(matched) != 3:
            raise ValueError('public matched inventory')
        for item in matched[1:]:
            if item['total_source_bytes'] != matched[0]['total_source_bytes']:
                raise ValueError('public table requires equal source traffic')
        t = matched[0]
        cost = t['source_costs']
        rows.append([label, t['calls'], t['oracle_changes'],
                     f"{cost['acquisition'].get('bytes', 0):,}",
                     f"{cost['feed'].get('bytes', 0):,}", f"{cost['refill'].get('bytes', 0):,}"])
    table(paper/'generated/incremental_history_table.tex',
          'Published-history comparison with capacity 10 and two-event index lag.',
          'tab:incremental-history', ['Query stratum', 'Calls', 'Changed', 'Acquire B', 'Feed B', 'Refill B'], rows, check_only=check_only)
    rows = []
    for policy, label in [('continuation', 'Continuation'), ('extra-local', 'Local extra/refill'),
                          ('extra-global', 'Global extra/refill')]:
        matched = [t for t in generated if t['policy'] == policy and t['capacity'] == 5]
        if len(matched) != 2 or {t['seed'] for t in matched} != {2, 3}:
            raise ValueError('generated matched inventory')
        sums = [sum(t['source_costs'][phase].get('bytes', 0) for t in matched)
                for phase in ('acquisition', 'feed', 'refill')]
        total = sum(t['total_source_bytes'] for t in matched)
        if sum(sums) != total:
            raise ValueError('phase sum')
        rows.append([label]+[f'{v:,}' for v in sums]+[f'{total:,}', sum(t['refill_shards'] for t in matched)])
    table(paper/'generated/incremental_refill_table.tex',
          'Generated rank-churn comparison with capacity 5 and two-event index lag.',
          'tab:incremental-refill', ['Policy', 'Acquire B', 'Feed B', 'Refill B', 'Total B', 'Refills'], rows, check_only=check_only)
    print(json.dumps({'result': 'PASS', 'tables': 2}))


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--census-root', type=Path)
    main(parser.parse_args().census_root)
