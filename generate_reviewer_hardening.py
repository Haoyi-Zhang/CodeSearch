appendix=r'''\section{Reviewer-facing accounting and validity audit}
\label{app:reviewer-hardening}
\input{generated/reviewer_metrics_table}
\input{generated/reviewer_uncertainty_table}

\paragraph{What changes under the broader accounting.}
The continuation design remains below exact overlay and the cut-aware cache in both source-facing and end-to-end application bytes on the frozen primary workload.  The full mirror is different: it uses fewer end-to-end application bytes per query, while retaining roughly \ReviewerMirrorStateMultiple$\times$ as much maximum logical coordinator state.  We therefore report a Pareto trade-off rather than claiming that continuation universally dominates mirroring.  Logical state, process RSS, application bytes, and transport overhead are distinct quantities; none is silently converted into another.

\paragraph{Measurement contract.}
Source-facing bytes are the exact compact-JSON request and response lengths recorded at source RPC boundaries.  Client bytes are recomputed from frozen raw records as compact UTF-8 JSON containing only client-visible result, status, certificate, and failure fields.  Oracle labels, timing, debug fields, and instrumentation counters are excluded.  End-to-end application bytes are the sum.  TCP/IP, TLS, allocator metadata, and process startup are outside this metric and are not estimated.

\paragraph{Finite-trace uncertainty.}
The paired bootstrap resamples complete trace-level differences with a fixed seed.  The intervals are descriptive sensitivity summaries for the finite scenario/seed set, not confidence intervals for an assumed iid production population and not $p$-values.

\paragraph{History cutoff.}
The public-history experiment remains a deliberately frozen function-level projection through cachetools v7.1.8 (commit \texttt{4500e3d}, 31 August 2026).  The repository subsequently released v7.2.0 (commit \texttt{3c082c6}, 16 September 2026).  That post-freeze release is recorded in the artifact's cutoff audit rather than silently folded into the prespecified result.  The experiment must therefore not be described as a current full-repository replay.

\paragraph{Unresolved external-validity boundaries.}
The evidence does not establish WAN performance, durable multi-host recovery, production code-search relevance, hostile-source security, or generality beyond the frozen ranker and workloads.  These are explicit non-claims, not inferred successes.  The artifact's reviewer matrix identifies the experiment or assumption needed to cross each boundary.
'''
