for p,r in main.items():
    if p!='unsafe_stale' and not r: raise SystemExit(f'missing main row: {p}')

def src(r):
    x=val(r,'mean','source','byte')
    return x if x is not None else val(r,'source','byte')
def cli(r): return r.get('mean_client_payload_bytes')
def total(r): return r.get('mean_end_to_end_application_bytes')
def msgs(r): return val(r,'mean','source','message') or val(r,'source','message')
def state(r):
    return val(r,'max','logical','state','byte') or val(r,'logical','state','byte')

def pct(a,b): return (1-a/b)*100 if a is not None and b not in (None,0) else None
