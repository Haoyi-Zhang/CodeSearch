def pick_main(policy):
    cand=[r for r in rows if r.get('policy')==policy and r.get('family')=='continuation_main']
    if not cand: cand=[r for r in rows if r.get('policy')==policy]
    # prefer rows with source mean and most query-like metric
    def score(r):
        q=max([float(v) for k,v in r.items() if isinstance(v,(int,float)) and 'quer' in k.lower()] or [0])
        has=1 if any('source' in k.lower() and 'byte' in k.lower() and 'mean' in k.lower() for k in r) else 0
        return (has,q,len(r))
    return max(cand,key=score) if cand else {}

def val(r,*parts):
    for k,v in r.items():
        kl=k.lower()
        if isinstance(v,(int,float)) and all(p in kl for p in parts): return float(v)
    return None
policies=['continuation_certificate','exact_delta_overlay','cut_aware_cache','full_coordinator_mirror','unsafe_stale']
